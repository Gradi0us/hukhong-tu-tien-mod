def legs_body(pos_pairs):
    """Dạng 2 không có root: dịch body + 2 chân cùng nhau."""
    return {b: {"position": pos_pairs} for b in ("body", "right_leg", "left_leg")}


def merge(*dicts):
    out = {}
    for d in dicts:
        for b, ch in d.items():
            out.setdefault(b, {}).update(ch)
    return out


