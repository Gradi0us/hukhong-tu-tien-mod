def kf(pairs):
    return {f"{t:.2f}".rstrip('0').rstrip('.') if t else "0.0": {"vector": list(v)} for t, v in pairs}


def anim(length, bones, loop=False):
    out = {"animation_length": length, "bones": {}}
    if loop:
        out["loop"] = True
    for bone, ch in bones.items():
        out["bones"][bone] = {k: kf(v) for k, v in ch.items()}
    return out


